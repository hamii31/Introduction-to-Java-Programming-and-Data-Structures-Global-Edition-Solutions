public class ArithmeticExpression {
    public static void main(String[] args) {
        int r = 1, a = 1, b = 1, c = 1, d = 1, t = 1;

        System.out.println(4 / (3 * (r + 34)) - 9 * (a + Math.abs(b * c)) + (3 + d * (2 + a)) / (a + b * d));
        System.out.println(5.5 * Math.pow((r + 2.5), 2.5 + t));
    }
}
